"""
probe_similar_setup_evidence.py
Wilson Evidence Engine.
Calculates historical nearest-neighbor Wilson Lower Bound for the current regime/state.
"""

import os
import sys
import numpy as np
from sklearn.neighbors import NearestNeighbors
from sklearn.linear_model import LogisticRegression
from sklearn.preprocessing import StandardScaler

sys.path.insert(0, os.path.dirname(os.path.dirname(__file__)))
from edge_probe import _load_bars, FEATURE_BUILDERS

def wilson_lower_bound(acc, n):
    if n == 0: return 0.0
    z = 1.96
    phat = acc
    return (phat + z*z/(2*n) - z * np.sqrt((phat*(1-phat)+z*z/(4*n))/n)) / (1 + z*z/n)

def main():
    days = 60
    bars = _load_bars(days)
    if bars is None: return
    n_bars = len(bars["close"])
    print(f"\n{n_bars} minute-bars loaded. Evaluating Similar Setup Evidence Engine.")
    
    # Target: Big Move (Selectivity) AND Direction (VPIN Contrarian Side Accuracy)
    # Actually, we want to know if the proposed Side by the VPIN selector will be correct.
    h = 5
    ret = np.zeros(n_bars)
    for i in range(n_bars - h):
        ret[i] = bars["close"][i+h] - bars["close"][i]
        
    vpin_raw = FEATURE_BUILDERS["vpin"](bars)[0][:, 0]
    vpin_z = (vpin_raw - np.nanmean(vpin_raw)) / np.nanstd(vpin_raw)
    side_vpin = np.where(vpin_z > 1.5, -1, np.where(vpin_z < -1.5, 1, 0))
    
    # State Vector Features
    sel_features = ["realized_vol", "intensity", "range_compression"]
    X_state = np.column_stack([FEATURE_BUILDERS[f](bars)[0] for f in sel_features])
    
    # We only care when a signal was generated by the side selector
    mask = (side_vpin != 0) & np.all(np.isfinite(X_state), axis=1)
    
    idx_signals = np.where(mask)[0]
    n_signals = len(idx_signals)
    print(f"Historical Signals (Base Strategy): {n_signals}")
    
    if n_signals < 500:
        print("Not enough signals to evaluate nearest neighbors.")
        return
        
    X_masked = X_state[idx_signals]
    y_correct = (np.sign(ret[idx_signals]) == side_vpin[idx_signals]).astype(int)
    
    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(X_masked)
    
    # Fit Nearest Neighbors
    k = 100
    nn = NearestNeighbors(n_neighbors=k)
    # We use a time-series split logic: for a point at index `i`, we only query points BEFORE `i`.
    # Since doing this efficiently in a loop takes time, we will sample 500 random points 
    # from the last 20% of the dataset and query their history.
    
    cut = int(n_signals * 0.8)
    history_X = X_scaled[:cut]
    history_y = y_correct[:cut]
    
    test_X = X_scaled[cut:]
    test_y = y_correct[cut:]
    
    nn.fit(history_X)
    distances, indices = nn.kneighbors(test_X)
    
    # For each test point, look at its K nearest historical neighbors and compute Wilson LB
    wilsons = []
    accuracies = []
    
    for i in range(len(test_X)):
        neighbor_idx = indices[i]
        neighbor_corrects = history_y[neighbor_idx]
        acc = np.mean(neighbor_corrects)
        w = wilson_lower_bound(acc, k)
        wilsons.append(w)
        accuracies.append(acc)
        
    wilsons = np.array(wilsons)
    
    print("\n--- Evidence Engine Results ---")
    print(f"Average Neighbor Accuracy: {np.mean(accuracies):.1%}")
    print(f"Average Wilson LB (k=100)  : {np.mean(wilsons):.1%}")
    
    # Can we use the Wilson LB to upgrade/downgrade?
    # If Wilson LB > 60%, what is the true forward accuracy?
    high_conf_mask = wilsons > 0.60
    if np.sum(high_conf_mask) > 0:
        true_acc_high = np.mean(test_y[high_conf_mask])
        print(f"\nForward Accuracy when Wilson LB > 60%: {true_acc_high:.1%} (N={np.sum(high_conf_mask)})")
    else:
        print("\n0 test signals had Wilson LB > 60%.")
        
    low_conf_mask = wilsons < 0.40
    if np.sum(low_conf_mask) > 0:
        true_acc_low = np.mean(test_y[low_conf_mask])
        print(f"Forward Accuracy when Wilson LB < 40%: {true_acc_low:.1%} (N={np.sum(low_conf_mask)})")

if __name__ == "__main__":
    main()
